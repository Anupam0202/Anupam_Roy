export const claimById = (id: string) => claims.find((c) => c.id === id);
/** A claim's text, cut at a word boundary to about `max` characters, for link labels in place of raw ids. */
export function claimShortTitle(id: string, max = 60): string {
  const c = claims.find((x) => x.id === id);
  if (!c) return "Evidence entry";
  if (c.claim.length <= max) return c.claim;
  const cut = c.claim.slice(0, max);
  return `${cut.slice(0, Math.max(cut.lastIndexOf(" "), 20)).replace(/[,;:.\s]+$/, "")}…`;
}
